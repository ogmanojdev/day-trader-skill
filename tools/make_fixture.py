#!/usr/bin/env python3
"""Generate a SYNTHETIC Yahoo-shaped 5-minute chart for an NSE session grid.

The suite must run offline and give the same numbers on every machine, and the
Time Machine needs 60 sessions of intraday bars to draw from. Yahoo's chart
endpoint throttles by IP hard enough that a test suite cannot depend on it, so
the fixture is generated, deterministically, and labelled synthetic in its own
filename and meta. It is not real RELIANCE data and no test should claim it is.

What it does reproduce, because the Time Machine's whole method rests on it, is
the shape of an Indian session: volatility is U-shaped, high in the first and
last half hour and lowest around 12:30. A flat-volatility fixture would let a
time-of-day bootstrap look identical to a uniform one and the test would prove
nothing.

    python3 tools/make_fixture.py --symbol DEMO --days 60 --out tests/fixtures/nse-timemachine
"""

import argparse
import datetime
import json
import math
import os
import random
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                                "nse-common"))
import nsecal  # noqa: E402


def vol_at(slot, bars):
    """U-shaped intraday volatility: 1.0 at the edges, about 0.35 at the lull."""
    x = (slot / max(1, bars - 1)) * 2.0 - 1.0          # -1 .. +1
    return 0.35 + 0.65 * (x * x) ** 0.8


def build(symbol, days, seed, start_price, drift, base_vol, end_day):
    rng = random.Random(seed)
    sessions = []
    d = end_day
    while len(sessions) < days:
        if nsecal.is_trading_day(d) and nsecal.covered(d):
            sessions.append(d)
        d -= datetime.timedelta(days=1)
        if (end_day - d).days > days * 4 + 60:
            break
    sessions.reverse()
    bars_per_day = nsecal.BARS_PER_DAY
    price = start_price
    ts, o_, h_, l_, c_, v_ = [], [], [], [], [], []
    for day in sessions:
        price *= 1.0 + rng.gauss(drift, base_vol * 3)   # overnight gap
        for slot, t in enumerate(nsecal.bar_slots(day)):
            vol = base_vol * vol_at(slot, bars_per_day)
            o = price
            c = o * (1.0 + rng.gauss(0.0, vol))
            wick = abs(rng.gauss(0.0, vol)) * o
            h = max(o, c) + wick * 0.6
            l = min(o, c) - wick * 0.6
            local = datetime.datetime.combine(day, t)
            ts.append(int((nsecal.ist_to_utc(local) - datetime.datetime(1970, 1, 1))
                          .total_seconds()))
            o_.append(round(o, 2))
            h_.append(round(h, 2))
            l_.append(round(l, 2))
            c_.append(round(c, 2))
            v_.append(int(abs(rng.gauss(90000, 40000)) * (0.5 + vol_at(slot, bars_per_day))))
            price = c
    return {"chart": {"error": None, "result": [{
        "meta": {"currency": "INR", "symbol": symbol + ".NS", "exchangeName": "NSI",
                 "fullExchangeName": "NSE", "instrumentType": "EQUITY",
                 "exchangeTimezoneName": "Asia/Kolkata", "timezone": "IST", "gmtoffset": 19800,
                 "regularMarketPrice": c_[-1] if c_ else None,
                 "dataGranularity": "5m", "range": "%dd" % days,
                 "_synthetic": True,
                 "_note": ("Generated by tools/make_fixture.py. Not real market data. "
                           "Seeded, so every machine gets the same bars.")},
        "timestamp": ts,
        "indicators": {"quote": [{"open": o_, "high": h_, "low": l_, "close": c_, "volume": v_}]}}]}}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--symbol", default="DEMO")
    ap.add_argument("--days", type=int, default=60)
    ap.add_argument("--seed", type=int, default=1909)
    ap.add_argument("--price", type=float, default=1300.0)
    ap.add_argument("--drift", type=float, default=0.0004)
    ap.add_argument("--vol", type=float, default=0.0022)
    ap.add_argument("--end", default="2026-11-09", help="last session in the fixture (IST date)")
    ap.add_argument("--out", default="tests/fixtures/nse-timemachine")
    a = ap.parse_args(argv)
    end = nsecal.parse_ist(a.end, "--end").date()
    doc = build(a.symbol, a.days, a.seed, a.price, a.drift, a.vol, end)
    os.makedirs(a.out, exist_ok=True)
    path = os.path.join(a.out, "chart-%s.NS-%dd-5m.json" % (a.symbol, a.days))
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(doc, fh, separators=(",", ":"))
    res = doc["chart"]["result"][0]
    n = len(res["timestamp"])
    print("wrote %s: %d bars, %d sessions, last close %.2f"
          % (path, n, n // nsecal.BARS_PER_DAY, res["indicators"]["quote"][0]["close"][-1]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
